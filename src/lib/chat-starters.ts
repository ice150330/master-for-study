/**
 * 冷启动引导问题（优化方向 C2）：
 * 空会话给三枚可一键发送的起步问题，按成长目标定制，降低第一次提问的门槛。
 */

export function starterPrompts(goal: string | null | undefined): string[] {
  const normalized = (goal ?? '').trim();
  if (!normalized) {
    return [
      '我想开始学一个新主题，先帮我规划第一周该学什么',
      '用你自己的话给我讲一个容易混淆的基础概念，并举个例子',
      '考考我：从我最可能薄弱的地方提一个问题',
    ];
  }
  if (/后端|服务端|backend/i.test(normalized)) {
    return [
      '后端工程师的学习主线该怎么排？帮我从当前水平出发规划',
      '数据库索引为什么会失效？结合例子讲清楚',
      'HTTP 缓存的几种策略分别适合什么场景？',
    ];
  }
  if (/前端|front/i.test(normalized)) {
    return [
      '前端学习主线该怎么排？帮我从当前水平出发规划',
      '浏览器从输入 URL 到渲染经历了什么？讲关键步骤',
      'React 的渲染机制里最容易踩的坑是什么？',
    ];
  }
  if (/算法|AI|人工智能|机器学习|深度学习/i.test(normalized)) {
    return [
      '算法与 AI 方向的学习主线该怎么排？帮我规划',
      '讲讲时间复杂度分析里最容易出错的地方',
      '梯度下降的直觉是什么？用一个类比讲明白',
    ];
  }
  if (/转行|求职|面试/i.test(normalized)) {
    return [
      '我想转行进入技术岗位，先帮我评估该补哪些基础',
      '模拟一场技术面试：从自我介绍开始逐步追问',
      '帮我梳理简历上最该突出的三个技术点',
    ];
  }
  if (/学生|在校|考研|保研/i.test(normalized)) {
    return [
      '帮我把这学期的课程串成一条学习主线',
      '用考试能拿分的方式讲一个我最近没学透的知识点',
      '帮我出三道递进难度的练习题检验掌握程度',
    ];
  }
  return [
    `围绕「${normalized}」，帮我规划一条学习主线`,
    `讲讲「${normalized}」里最核心的一个概念`,
    `考考我对「${normalized}」的理解，从基础开始提问`,
  ];
}
